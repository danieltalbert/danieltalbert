def export(obj, out_dir, name):
    os.makedirs(out_dir, exist_ok=True)
    path = os.path.join(out_dir, "%s.glb" % name)
    bpy.ops.object.select_all(action="DESELECT")
    obj.select_set(True)
    bpy.context.view_layer.objects.active = obj
    bpy.ops.export_scene.gltf(
        filepath=path,
        export_format="GLB",
        use_selection=True,
        export_yup=True,
        export_apply=True,
        export_animations=False,
    )
    tris = sum(len(p.vertices) - 2 for p in obj.data.polygons)
    print("PROP %-10s -> %s  (%d verts, ~%d tris)" % (
        name, path, len(obj.data.vertices), tris))
    return path


def main():
    argv = sys.argv[sys.argv.index("--") + 1:] if "--" in sys.argv else []
    out_dir = DEFAULT_OUT
    if "--out" in argv:
        out_dir = argv[argv.index("--out") + 1]
    out_dir = os.path.abspath(out_dir)

    for name, builder in PROPS.items():
        clear_scene()
        obj = builder()
        export(obj, out_dir, name)
    print("make_props: %d prop(s) written to %s" % (len(PROPS), out_dir))


if __name__ == "__main__":
    main()
