"""Blender script: build Gradientfall's hand-props as high-quality glTF meshes.

Run headless (no .blend needed — the script builds everything from scratch):

    blender --background --python tools/make_props.py

or to write somewhere else:

    blender --background --python tools/make_props.py -- --out C:/path/to/props

Why this exists
---------------
The world's *terrain* is procedural and looks it in a good way — grass, rock,
snow and cloud all carry real shading detail. The hand-made objects did not:
the well, the wagon and the cottages were assembled in GDScript out of
axis-aligned boxes and cylinders, which reads as programmer-art next to the
landscape. Godot is a poor place to author that kind of geometry; Blender is
the right tool, and the project already has a Blender -> .glb pipeline for
Kern's base mesh (tools/export_kern_base.py).

Every prop here is generated by code rather than modelled by hand, so it stays
reproducible and reviewable — but it uses the things a mesh modeller gets and a
box-stacker does not:

  - **Bevelled edges** on everything. Real objects have no infinitely sharp
    corners; a 1-2 mm bevel is the single biggest step from "box" to "object"
    because it gives every edge a specular highlight.
  - **Radial and swept construction** — a well built from wedge-shaped stones
    around a circle, a wagon tilt swept along an arc, wheels with real spokes.
  - **Subdivision** where the form is soft (canvas, thatch, sacks).
  - **Deliberate irregularity**: per-element jitter in position, rotation and
    scale, so a stone ring or a shingle course never repeats exactly.
  - **PBR materials** with sensible roughness, exported in the glTF so Godot
    lights them properly instead of flat-shading a vertex colour.

Conventions (matched to the rest of the project)
------------------------------------------------
  - Metres, +Y up on export (Blender's +Z up is converted by the exporter).
  - Every prop stands on the origin with its base at Z=0, so Godot can drop it
    straight onto terrain height with no offset guessing.
  - One .glb per prop in game/assets/models/props/.
  - Transforms applied; no hidden scale rides into the engine.

Adding a prop: write a `build_*` function that returns the finished object(s),
register it in PROPS, and re-run. Nothing here is scene-specific.
"""

