def clear_scene():
    """Empty the file so each prop is exported in isolation."""
    bpy.ops.object.select_all(action="SELECT")
    bpy.ops.object.delete(use_global=False)
    for block in (bpy.data.meshes, bpy.data.materials, bpy.data.objects):
        for item in list(block):
            if item.users == 0:
                block.remove(item)


def material(name, colour, roughness=0.85, metallic=0.0):
    """A plain PBR material. glTF carries these straight into Godot."""
    mat = bpy.data.materials.get(name)
    if mat is None:
        mat = bpy.data.materials.new(name)
        mat.use_nodes = True
        bsdf = mat.node_tree.nodes["Principled BSDF"]
        bsdf.inputs["Base Color"].default_value = (*colour, 1.0)
        bsdf.inputs["Roughness"].default_value = roughness
        bsdf.inputs["Metallic"].default_value = metallic
        # Thin, open geometry — canvas skins, roof shingles, sails — is seen
        # from both faces in game. glTF exports single-sided by default, which
        # makes those surfaces vanish from behind.
        mat.use_backface_culling = False
    return mat


def add_mesh(name, verts, faces, mat=None):
    mesh = bpy.data.meshes.new(name)
    mesh.from_pydata(verts, [], faces)
    mesh.validate()
    obj = bpy.data.objects.new(name, mesh)
    bpy.context.collection.objects.link(obj)
    if mat is not None:
        obj.data.materials.append(mat)
    return obj


def box(name, size, location, mat=None, rotation=(0.0, 0.0, 0.0)):
    """An axis-aligned box, later bevelled by `finish`."""
    bpy.ops.mesh.primitive_cube_add(size=1.0, location=location)
    obj = bpy.context.active_object
    obj.name = name
    obj.scale = Vector(size) * 0.5
    obj.rotation_euler = rotation
    if mat is not None:
        obj.data.materials.append(mat)
    return obj


def cylinder(name, radius, depth, location, mat=None, rotation=(0.0, 0.0, 0.0),
             verts=24):
    bpy.ops.mesh.primitive_cylinder_add(
        radius=radius, depth=depth, location=location, vertices=verts
    )
    obj = bpy.context.active_object
    obj.name = name
    obj.rotation_euler = rotation
    if mat is not None:
        obj.data.materials.append(mat)
    return obj


def sphere(name, radius, location, mat=None, segments=20, rings=12):
    bpy.ops.mesh.primitive_uv_sphere_add(
        radius=radius, location=location, segments=segments, ring_count=rings
    )
    obj = bpy.context.active_object
    obj.name = name
    if mat is not None:
        obj.data.materials.append(mat)
    return obj


def bevel(obj, width=0.012, segments=2):
    """The single most important upgrade over box-stacking: no sharp edges."""
    mod = obj.modifiers.new("Bevel", "BEVEL")
    mod.width = width
    mod.segments = segments
    mod.limit_method = "ANGLE"
    mod.angle_limit = math.radians(40.0)
    mod.harden_normals = False
    return obj


def subsurf(obj, levels=1):
    mod = obj.modifiers.new("Subdivision", "SUBSURF")
    mod.levels = levels
    mod.render_levels = levels
    return obj


def shade_smooth(obj, angle=35.0):
    """Auto-smooth: soft on curves, crisp on real corners."""
    for poly in obj.data.polygons:
        poly.use_smooth = True
    mod = obj.modifiers.new("SmoothByAngle", "NODES")
    try:
        bpy.ops.object.select_all(action="DESELECT")
        obj.select_set(True)
        bpy.context.view_layer.objects.active = obj
        bpy.ops.object.modifier_remove(modifier=mod.name)
        bpy.ops.object.shade_auto_smooth(angle=math.radians(angle))
    except Exception:
        # Older/newer API surface: smooth shading alone is an acceptable
        # fallback, the bevel still carries the edge highlights.
        pass
    return obj


def join(objs, name):
    """Join a prop's parts into one object so Godot gets a single mesh."""
    objs = [o for o in objs if o is not None]
    bpy.ops.object.select_all(action="DESELECT")
    for obj in objs:
        obj.select_set(True)
    bpy.context.view_layer.objects.active = objs[0]
    bpy.ops.object.join()
    joined = bpy.context.active_object
    joined.name = name
    return joined


def finish(obj, name):
    """Apply modifiers and transforms, sit the prop's base on Z=0."""
    bpy.ops.object.select_all(action="DESELECT")
    obj.select_set(True)
    bpy.context.view_layer.objects.active = obj
    for mod in list(obj.modifiers):
        try:
            bpy.ops.object.modifier_apply(modifier=mod.name)
        except RuntimeError:
            obj.modifiers.remove(mod)
    bpy.ops.object.transform_apply(location=False, rotation=True, scale=True)
    # Every prop is authored standing on z=0 already. Do NOT re-seat it on its
    # lowest vertex: parts that are deliberately below ground (the well shaft)
    # would then define the floor and hoist the whole object into the air.
    bpy.ops.object.transform_apply(location=True, rotation=False, scale=False)
    obj.name = name
    return obj


def jitter(index, seed, amount):
    """Deterministic pseudo-random wobble — repeatable across runs."""
    value = math.sin((index + 1) * 12.9898 + seed * 78.233) * 43758.5453
    return (value - math.floor(value) - 0.5) * 2.0 * amount


